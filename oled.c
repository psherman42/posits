#define RST_N   0
#define DC      1

void oled_init (uint32_t hfclk_hz, uint32_t spiclk_hz)
{
  uint32_t i;

  gpio_dir( RST_N, GPIO_OUT );
  gpio_dir( DC, GPIO_OUT );

  gpio_iof( RST_N, GPIO_GPIO );
  gpio_iof( DC, GPIO_GPIO );

  spi1_init( hfclk_hz, spiclk_hz );

  // SSD1306

  gpio_low( RST_N );  // Reset
  for(i=0; i<1000000; i++) {i+=1;i-=1;}
  gpio_high( RST_N );  // Normal

  gpio_low( DC );  // Command

  spi1_start( 0 );
  spi1_transfer( 0xAE );
  spi1_transfer( 0xD5 ); spi1_transfer( 0x80 );
  spi1_transfer( 0xA8 ); spi1_transfer( 63 );  // H-1
  spi1_transfer( 0xD3 ); spi1_transfer( 0 );
  spi1_transfer( 0x40 | 0x00 );  // 0x40-0x7F, 0-63
  spi1_transfer( 0x8D ); spi1_transfer( 0x14 );
  spi1_transfer( 0x20 ); spi1_transfer( 2 );  // mem-mode: 0=horiz, 1=vert, 2=page
  spi1_transfer( 0xA0 | 0x01 );
  spi1_transfer( 0xC8 );  // or 0xC0
  spi1_transfer( 0xDA ); spi1_transfer( 0x12 );  //0x12  Ena/Dis ... Alt/Seq
  spi1_transfer( 0x81 ); spi1_transfer( 127 );  // or 0xCF
  spi1_transfer( 0xD9 ); spi1_transfer( 0x22 );
  spi1_transfer( 0xDB ); spi1_transfer( 0x20 );
  spi1_transfer( 0xA4 );
  spi1_transfer( 0xA6 );
  spi1_transfer( 0x2E );
  spi1_transfer( 0xAF );
  spi1_stop( 0 );

  //while (gpio_read( BUSY_N ) == 0) for(i=0; i<1000; i++) {i+=1;i-=1;}
  for(i=0; i<10000; i++) {i+=1;i-=1;}

  _xpos = 0;
  _ypos = 0;
}

void oled_clear_display (void)
{
  uint16_t i, pg;

  //spi1_transfer( 0x21 ); spi1_transfer( 0 ); spi1_transfer( 127 );  // vert 0..W-1
  //spi1_transfer( 0x22 ); spi1_transfer( 0 ); spi1_transfer( 3 );  // horiz 0..7

  for (pg=0; pg<8; pg++)
  {
    spi1_start( 0 );
    gpio_low( DC );  // Command
    spi1_transfer( 0xB0 | pg );
    spi1_transfer( 0x00 );  // lower nibble
    spi1_transfer( 0x10 );  // upper nibble
    spi1_stop( 0 );
    spi1_start( 0 );
    gpio_high( DC );  // Data
    for (i=0; i<128; i++)
    {
      spi1_transfer( 0x00 );  // black
    }
    spi1_stop( 0 );
    //while (gpio_read( BUSY_N ) == 0) for(i=0; i<1000; i++) {i+=1;i-=1;}
  }

  _xpos = 0;
  _ypos = 0;
}

