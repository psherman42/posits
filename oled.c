void oled_plot_char (char c, uint8_t x, uint8_t y)
{
  spi1_start( 0 );
  gpio_low( DC );  // Command
  spi1_transfer( 0xB0 | y );
  spi1_transfer( 0x00 | ((x >> 0) & 0x0F) );  // lower nibble
  spi1_transfer( 0x10 | ((x >> 4) & 0x0F) );  // upper nibble
  spi1_stop( 0 );
  spi1_start( 0 );
  gpio_high( DC );  // Data
  spi1_transblk( 5, &charmap[c - ' '][0], NULL );  // charmap offset is <space>
  spi1_stop( 0 );
}

void oled_write (char c)
{
  if (c == 0x7F) c = 0x08;  // change DEL to BS

  if (c < ' ')  // space
  {
    switch (c)
    {
      case 0x08:  // backspace
        if (_xpos == 0) { _ypos--; _xpos = 127-5; }
        else
        {
          _xpos -= 1;  // inter-char spacing
          _xpos -= 5;
        }
        oled_plot_char( ' ', _xpos, _ypos );
        break;

      case 0x0D:  // carriage return
      case 0x0A:  // line feed
        _xpos = 0;
        if (_ypos == 7) _ypos = 0; else _ypos++;
        break;

      default:  // other non-printable
        break;
    }
  }
  else
  {
    oled_plot_char( c, _xpos, _ypos );
    _xpos += 1;  // inter-char spacing
    _xpos += 5;

    if (_xpos > 127) { _xpos = 0; _ypos++; }
    if (_ypos > 7) { _ypos = 0; }
  }
}

void oled_set_pos (uint8_t x, uint8_t y)
{
  _xpos = x;
  _ypos = y;
}

void oled_write_string (char *s)
{
  while (*s != '\0')
  {
    oled_write( *s++ );
  }
}

enum color_t _color=COLOR_WHITE;
int8_t x_origin=64;//W=128
int8_t y_origin=32;//H=64

int8_t x0;
int8_t y0;

void oled_plot_point (uint8_t x, uint8_t y)
{
  uint8_t row, col;
  uint8_t bit;

  row = y;
  col = x;
  bit = row & 0x07;

  spi1_start( 0 );
  gpio_low( DC );  // Command
  spi1_transfer( 0xB0 | (row >> 3) );
  spi1_transfer( 0x00 | ((col >> 0) & 0x0F) );  // lower nibble
  spi1_transfer( 0x10 | ((col >> 4) & 0x0F) );  // upper nibble
  spi1_stop( 0 );
  spi1_start( 0 );
  gpio_high( DC );  // Data
  spi1_transfer( _color << bit );
  spi1_stop( 0 );
}

void _oled_plot_point (int16_t x, int16_t y)
{
  int16_t row, col;

  row = 64 - y - y_origin;
  col = x + x_origin;

  oled_plot_point( x, y );
}

void oled_origin (int16_t x, int16_t y)
{
  x_origin = 64 + x;  // W=128
  y_origin = 32 + y;  // H=64
}

void oled_color (enum color_t c)
{
  _color = c;
}

void oled_move_to (int16_t x, int16_t y)
{
  x0 = x;
  y0 = y;
}

int16_t abs (int16_t n) { return n * ((2*n+1) % 2); }

void oled_draw_to ( int16_t x, int16_t y)
{
  int16_t sx, sy, e2, err;
  int16_t dx, dy;

  dx = abs(x - x0);
  dy = abs(y - y0);

  if (x0 < x) sx = 1; else sx = -1;
  if (y0 < y) sy = 1; else sy = -1;
  err = dx - dy;
  for (;;)
  {
    _oled_plot_point( x0, y0 );
    if ((x0 == x) && (y0 == y)) return;
    e2 = err << 1;

    if (e2 > -dy)
    {
      err = err - dy;
      x0 = x0 + sx; 
    }

    if (e2 < dx)
    {
      err = err + dx;
      y0 = y0 + sy; 
    }
  }
}

void oled_draw_circle (int16_t r)
{
  int16_t i, x, y;

  x = -r << 9;
  y = 0;

  for (i=0; i<=360; i++)
  {
    oled_move_to( (x>>9), (y>>9) );
    x = x + ((y>>9) * 16);
    y = y - ((x>>9) * 16);
    oled_draw_to( x>>9, y>>9 );
    //_oled_plot_point( x0 + (x>>9), y0 + (y>>9) );
  }
}

