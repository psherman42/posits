/* -- LDL* decomposition ----------------------------------------- */
/* A = L * D * L^T
 * No sqrt. Every inner loop is dot(row, row, k) weighted by d[].
 * Pass dot and sum function pointers -- naive or exact.          */

int ldl_decomp(double A[MAXN][MAXN], double L[MAXN][MAXN],
               double d[MAXN], int n, dotfn dot, sumfn sm) {
    int i, j, k;
    double tmp[MAXN];

    memset(L, 0, sizeof(double)*MAXN*MAXN);

    for (j = 0; j < n; j++) {
        /* d[j] = A[j][j] - sum_{k<j} L[j][k]^2 * d[k] */
        for (k = 0; k < j; k++) tmp[k] = L[j][k] * L[j][k] * d[k];
        d[j] = A[j][j] - sm(tmp, j);
        L[j][j] = 1.0;

        if (fabs(d[j]) < 1e-300) return -1; /* singular */

        for (i = j+1; i < n; i++) {
            /* L[i][j] = (A[i][j] - sum_{k<j} L[i][k]*L[j][k]*d[k]) / d[j] */
            for (k = 0; k < j; k++) tmp[k] = L[i][k] * L[j][k] * d[k];
            L[i][j] = (A[i][j] - sm(tmp, j)) / d[j];
        }
    }
    return 0;
}

/* -- solve L*D*L^T * x = b ------------------------------------- */
/* Three passes: forward (Ly=b), diagonal (Dz=y), backward (L^Tx=z) */

void ldl_solve(double L[MAXN][MAXN], double d[MAXN],
               double b[MAXN], double x[MAXN],
               int n, dotfn dot, sumfn sm) {
    double y[MAXN], z[MAXN], tmp[MAXN];
    int i, k;

    /* forward substitution: Ly = b */
    for (i = 0; i < n; i++) {
        for (k = 0; k < i; k++) tmp[k] = L[i][k] * y[k];
        y[i] = b[i] - sm(tmp, i);
    }

    /* diagonal scaling: z = D^-1 * y */
    for (i = 0; i < n; i++) z[i] = y[i] / d[i];

    /* backward substitution: L^T x = z */
    for (i = n-1; i >= 0; i--) {
        for (k = i+1; k < n; k++) tmp[k-i-1] = L[k][i] * x[k];
        x[i] = z[i] - sm(tmp, n-i-1);
    }
}

