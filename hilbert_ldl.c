/*
 * hilbert_ldl.c -- LDL* decomposition on scaled Hilbert matrices
 *
 * Type this in. Compile. Run. See what happens.
 *
 *   cc -o hilbert_ldl hilbert_ldl.c -lm && ./hilbert_ldl
 *
 * LDL* avoids the square-root rounding in Cholesky (LL*).
 * A = L * D * L^T  where D is diagonal, L is unit lower triangular.
 * No sqrt anywhere. Every inner product is a dot product or a sum.
 * That is exactly where a quire accumulator helps.
 *
 * John Gustafson (unpublished DARPA report, 2024):
 * exact inversion of H(N) achievable up to N=12 with LDL* + quire.
 * Plain Cholesky fails at N=7 due to sqrt rounding.
 *
 * Uses microuniversal.h: four primitives, two typedefs.
 * dot is the M. sum is the A. Together they are the MAC.
 * Swap dot_naive/sum_naive for dot_exact/sum_exact to engage
 * the quire. The algorithm does not change.
 *
 * Scaling: full LCM for exact integer entries, then divide by 2^k
 * to keep entries in [0.5, 1.0] -- posit maximum accuracy region.
 */

