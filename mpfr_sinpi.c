#include <stdio.h>
#include <mpfr.h>
#include "/home/labuser/posits/posit_trig56.h"

int main(void){
    positenv_init(32,2);
    
    /* all unique hard cases -- fractional parts in [0, 0.5] */
    uint32_t hard_cases[] = {
        0x00000001,  /* Taylor: minpos */
        0x0abc89a0,  /* Taylor: 6.68e-4 */
        0x1773b1a8,  /* Taylor: 1.46e-2 */
        /* CORDIC cases: */
        0x1da617dc, 0x1e89f642, 0x1fc079d4, 0x1fd02542,
        0x2163fc4b, 0x227597b5, 0x237e939f, 0x24d4c10e,
        0x258da57c, 0x29d35879, 0x2a3770dd, 0x2c5f4740,
        0x2d9a4243, 0x2e46ed11, 0x2f84e299, 0x2f8eeb23,
        0x300f1827, 0x31129cb7, 0x3118eed9, 0x3421c0e3,
        0x361158ae,
        /* large values with same fractional part */
        0x48c5f474, 0x5062fa3a, 0x5462fa3a,
        0x58317d1d, 0x5a317d1d, 0x5c317d1d, 0x5e317d1d,
    };
    int n = sizeof(hard_cases)/sizeof(hard_cases[0]);
    
    mpfr_t x, y, pi;
    mpfr_init2(x, 200);
    mpfr_init2(y, 200);
    mpfr_init2(pi, 200);
    mpfr_const_pi(pi, MPFR_RNDN);
    
    printf("/* sin_pi56 hard case lookup table -- generated by mpfr_sinpi.c */\n");
    printf("/* %d entries, each {input_posit32, correctly_rounded_output} */\n", n);
    printf("static const uint32_t _sin_pi_hard[][2] = {\n");
    
    int i;
    for(i=0; i<n; i++){
        uint32_t p = hard_cases[i];
        double ad = posit_to_double(p);
        
        /* compute sin(pi * ad) at 200-bit precision */
        mpfr_set_d(x, ad, MPFR_RNDN);
        mpfr_mul(x, x, pi, MPFR_RNDN);
        mpfr_sin(y, x, MPFR_RNDN);
        
        /* round to nearest double then to nearest posit32 */
        double result = mpfr_get_d(y, MPFR_RNDN);
        uint32_t correct = posit_from_double(result);
        uint32_t ours    = posit32_sin_pi56(p);
        
        printf("    { 0x%08x, 0x%08x },  /* a=%.15e ours=0x%08x %s */\n",
               p, correct, ad, ours,
               correct==ours ? "OK" : "FIXED");
    }
    printf("};\n");
    printf("#define N_SIN_PI_HARD %d\n", n);
    
    mpfr_clear(x); mpfr_clear(y); mpfr_clear(pi);
    return 0;
}
