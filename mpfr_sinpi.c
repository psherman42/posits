#include <stdio.h>
#include <mpfr.h>
#include "/home/labuser/posits/posit_trig56.h"

int main(void){
    positenv_init(32,2);

    uint32_t hard_cases[500];
    int n = 0;
    char line[32];
    while(fgets(line, sizeof(line), stdin)){
        uint32_t v;
        if(sscanf(line, "%x", &v) == 1 || sscanf(line, "0x%x", &v) == 1)
            hard_cases[n++] = v;
    }

    mpfr_t x, y, pi, pv, err_best, err_cand;
    mpfr_init2(x,        200);
    mpfr_init2(y,        200);
    mpfr_init2(pi,       200);
    mpfr_init2(pv,       200);
    mpfr_init2(err_best, 200);
    mpfr_init2(err_cand, 200);
    mpfr_const_pi(pi, MPFR_RNDN);

    printf("/* sin_pi_hard.h -- correctly-rounded hard cases for posit32_sin_pi56\n");
    printf(" * Generated by mpfr_sinpi.c using MPFR 4.2.2 at 200-bit precision.\n");
    printf(" * %d entries: nearest-posit32 via neighbor comparison, no double-rounding.\n", n);
    printf(" * Total storage: %d * 8 bytes = %d bytes\n", n, n*8);
    printf(" * 2026-11-16 pds/claude -- Pioneer got-milk SG2042\n");
    printf(" */\n");
    printf("static const uint32_t _sin_pi_hard[][2] = {\n");

    int i;
    for(i = 0; i < n; i++){
        uint32_t p = hard_cases[i];
        double ad = posit_to_double(p);

        /* compute sin(pi * ad) at 200-bit precision */
        mpfr_set_d(x, ad, MPFR_RNDN);
        mpfr_mul(x, x, pi, MPFR_RNDN);
        mpfr_sin(y, x, MPFR_RNDN);

        /* avoid double-rounding: pick nearest posit32 by neighbor comparison */
        double d = mpfr_get_d(y, MPFR_RNDN);
        uint32_t c = posit_from_double(d);
        uint32_t best = c;
        uint32_t k;

        /* |posit_to_double(best) - y| */
        mpfr_set_d(err_best, posit_to_double(best), MPFR_RNDN);
        mpfr_sub(err_best, err_best, y, MPFR_RNDN);
        mpfr_abs(err_best, err_best, MPFR_RNDN);

        /* try c+1 */
        k = c + 1;
        mpfr_set_d(pv, posit_to_double(k), MPFR_RNDN);
        mpfr_sub(err_cand, pv, y, MPFR_RNDN);
        mpfr_abs(err_cand, err_cand, MPFR_RNDN);
        if(mpfr_cmp(err_cand, err_best) < 0){
            best = k;
            mpfr_set(err_best, err_cand, MPFR_RNDN);
        }

        /* try c-1 */
        if(c > 0){
            k = c - 1;
            mpfr_set_d(pv, posit_to_double(k), MPFR_RNDN);
            mpfr_sub(err_cand, pv, y, MPFR_RNDN);
            mpfr_abs(err_cand, err_cand, MPFR_RNDN);
            if(mpfr_cmp(err_cand, err_best) < 0)
                best = k;
        }

        uint32_t correct = best;
        uint32_t ours    = posit32_sin_pi56(p);

        printf("    { 0x%08x, 0x%08x },  /* a=%.15e %s */\n",
               p, correct, ad,
               correct==ours ? "OK" : "FIXED");
    }
    printf("};\n");
    printf("#define N_SIN_PI_HARD %d\n", n);

    mpfr_clear(x); mpfr_clear(y); mpfr_clear(pi);
    mpfr_clear(pv); mpfr_clear(err_best); mpfr_clear(err_cand);
    return 0;
}
